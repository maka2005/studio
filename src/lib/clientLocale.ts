export const clientMessages: Record<Locale, ClientMessages> = { ru, kk };

/** Единый доступ к клиентским строкам: ?lang=kk и переключатель действуют без перезагрузки. */
export function useClientMessages() {
  const { locale } = useLocale();
  return { locale, m: clientMessages[locale] };
}

export const clientDateLocale = (locale: Locale) => (locale === 'kk' ? kkDate : ruDate);

/** Код ошибки из API → локализованное сообщение. */
export function clientErrText(error: unknown, errors: ErrorMessages): string {
  const message = String((error as Error)?.message ?? error ?? '');
  const code = Object.keys(errors)
    .filter((key) => key !== 'default' && message.includes(key))
    .sort((a, b) => b.length - a.length)[0];
  return (code && errors[code]) || errors.default;
}
